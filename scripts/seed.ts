// Deterministic generator for the sample pack (architecture §seed.ts): reads evals/queries/sample/*.sql, checks every precondition
// against the committed data on DuckDB (non-vacuity, ORDER BY keys unique, each trap's tempting rewrite really changes the rows and
// the hero's rewrite really does not — by an EXCEPT ALL oracle independent of the Verifier), writes PRECONDITIONS.md and renders
// input_examples/example_1..6.json. A query whose precondition fails is refused, nothing is written.
// usage: npx tsx scripts/seed.ts [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "../src/config.js";
import { DuckDbEngine } from "../src/engine/duckdb.js";

const PACK = join(ROOT, "evals", "queries", "sample");
const read = (f: string) => readFileSync(join(PACK, f), "utf8").trim() + "\n";
const strip = (sql: string) => sql.split("\n").filter((l) => !l.trim().startsWith("--")).join("\n").trim();
const check = process.argv.includes("--check");

type Kind = "equivalent" | "differs" | "none";
const QUERIES: { file: string; rewrite?: string; rewriteIs: Kind; orderKey?: string[]; nonVacuous: boolean }[] = [
  { file: "01-hero.sql", rewrite: "01-hero.rewrite.sql", rewriteIs: "equivalent", orderKey: ["Borough"], nonVacuous: true },
  { file: "02-hero-sibling.sql", rewriteIs: "none", orderKey: ["Borough"], nonVacuous: true },
  { file: "03-trap-left-join.sql", rewrite: "03-trap-left-join.rewrite.sql", rewriteIs: "differs", orderKey: ["LocationID"], nonVacuous: true },
  { file: "04-trap-union.sql", rewrite: "04-trap-union.rewrite.sql", rewriteIs: "differs", nonVacuous: true },
  { file: "05-trap-not-in.sql", rewrite: "05-trap-not-in.rewrite.sql", rewriteIs: "differs", orderKey: ["LocationID"], nonVacuous: true },
  { file: "06-no-gain-control.sql", rewrite: "06-no-gain-control.rewrite.sql", rewriteIs: "equivalent", orderKey: ["payment_type"], nonVacuous: true },
  { file: "08-control.sql", rewriteIs: "none", orderKey: ["Borough"], nonVacuous: true },
];

const engine = await DuckDbEngine.open();
const lines: string[] = ["# Sample pack preconditions", "", "Generated by `scripts/seed.ts` against `data/sample/` — do not edit.", "", "| Query | Rows | ORDER BY keys unique | Tempting / hand rewrite | Oracle (`EXCEPT ALL` both ways) |", "|---|---|---|---|---|"];
const failures: string[] = [];
const rowsOf = async (sql: string) => (await engine.run(sql, { drain: true, rowCap: 1_000_000 })).rows;

for (const q of QUERIES) {
  const sql = strip(read(q.file));
  const rows = await rowsOf(sql);
  if (q.nonVacuous && (rows.length === 0 || rows.every((r) => r.every((v) => v === null)))) failures.push(`${q.file}: result is empty or all NULL`);
  let uniq = "n/a (multiset)";
  if (q.orderKey) {
    const keys = (await engine.run(sql, { drain: true, rowCap: 1 })).columns.map((c) => c.name);
    const idx = q.orderKey.map((k) => keys.findIndex((c) => c.toLowerCase() === k.toLowerCase()));
    if (idx.some((i) => i < 0)) failures.push(`${q.file}: ORDER BY key not an output column`);
    else {
      const seen = new Set(rows.map((r) => JSON.stringify(idx.map((i) => r[i]))));
      uniq = seen.size === rows.length ? "yes" : "NO";
      if (seen.size !== rows.length) failures.push(`${q.file}: ORDER BY keys not unique on the shipped data`);
    }
  }
  let oracle = "—";
  let rwNote = "—";
  if (q.rewrite) {
    const rw = strip(read(q.rewrite));
    const ab = (await rowsOf(`SELECT count(*) FROM ((${sql.replace(/\bORDER BY[\s\S]*$/i, "")}) EXCEPT ALL (${rw.replace(/\bORDER BY[\s\S]*$/i, "")}))`))[0]![0];
    const ba = (await rowsOf(`SELECT count(*) FROM ((${rw.replace(/\bORDER BY[\s\S]*$/i, "")}) EXCEPT ALL (${sql.replace(/\bORDER BY[\s\S]*$/i, "")}))`))[0]![0];
    const same = Number(ab) === 0 && Number(ba) === 0;
    oracle = `${ab} / ${ba} → ${same ? "equal" : "differ"}`;
    rwNote = q.rewriteIs;
    if ((q.rewriteIs === "equivalent") !== same) failures.push(`${q.file}: rewrite expected ${q.rewriteIs} but the oracle says ${same ? "equal" : "differ"}`);
  }
  lines.push(`| \`${q.file}\` | ${rows.length} | ${uniq} | ${rwNote} | ${oracle} |`);
}
// T1/T3 trap preconditions in plain numbers
const zonesNoCash = Number((await rowsOf("SELECT count(*) FROM ops.zones z WHERE NOT EXISTS (SELECT 1 FROM lake.trips t WHERE t.PULocationID = z.LocationID AND t.payment_type = 2)"))[0]![0]);
const nullRate = Number((await rowsOf("SELECT count(*) FROM lake.trips WHERE RatecodeID IS NULL"))[0]![0]);
const dupRows = Number((await rowsOf("SELECT (SELECT count(*) FROM (SELECT PULocationID, payment_type, passenger_count FROM lake.trips WHERE trip_distance > 30 UNION ALL SELECT PULocationID, payment_type, passenger_count FROM lake.trips WHERE fare_amount > 100)) - (SELECT count(*) FROM (SELECT PULocationID, payment_type, passenger_count FROM lake.trips WHERE trip_distance > 30 UNION SELECT PULocationID, payment_type, passenger_count FROM lake.trips WHERE fare_amount > 100))"))[0]![0]);
if (zonesNoCash < 1) failures.push("T1 precondition false: every zone has a cash trip");
if (nullRate < 1) failures.push("T3 precondition false: RatecodeID has no NULLs");
if (dupRows < 1) failures.push("T2 precondition false: the UNION branches share no duplicate rows");
lines.push("", `- T1: ${zonesNoCash} zone(s) have no cash trip, so moving the payment filter to WHERE drops them.`, `- T2: UNION ALL returns ${dupRows} more row(s) than UNION.`, `- T3: ${nullRate} trip(s) have a NULL RatecodeID.`, "- 07-nondeterministic.sql: LIMIT without ORDER BY (expected NOT_VERIFIABLE, not executed here).");
await engine.close();

if (failures.length) {
  console.error("seed: refused —\n  " + failures.join("\n  "));
  process.exit(1);
}
if (check) {
  console.log("seed --check: all preconditions hold");
  process.exit(0);
}
writeFileSync(join(PACK, "PRECONDITIONS.md"), lines.join("\n") + "\n");

const body = (sql: string, playbook: "empty" | "seed", candidate?: string) =>
  JSON.stringify({ input: { sql: strip(sql), ...(candidate ? { candidate_sql: strip(candidate) } : {}), source: "paste" }, options: { sample_mode: true, playbook } }, null, 2) + "\n";
const ex: [string, string][] = [
  // Names follow the spec's swap rule: the canonical record pass showed the model avoiding T1 (0 of 5 first attempts refused), so the
  // Hub step-9 example_1 is the deterministic refusal of the tempting rewrite and example_2 is the plain-SQL run.
  ["example_1", body(read("03-trap-left-join.sql"), "empty", read("03-trap-left-join.rewrite.sql"))],
  ["example_2", body(read("03-trap-left-join.sql"), "empty")],
  ["example_3", body(read("03-trap-left-join.sql"), "seed", read("03-trap-left-join.rewrite.sql"))],
  ["example_4", body(read("01-hero.sql"), "empty")],
  ["example_5", body(read("07-nondeterministic.sql"), "empty")],
  ["example_6", body(read("06-no-gain-control.sql"), "empty")],
];
for (const [name, text] of ex) writeFileSync(join(ROOT, "input_examples", `${name}.json`), text);
console.log(`seed: ${QUERIES.length} queries checked, PRECONDITIONS.md and ${ex.length} input examples written`);
